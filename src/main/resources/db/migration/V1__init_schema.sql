CREATE TABLE users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50)  NOT NULL UNIQUE,
    email    VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role     VARCHAR(20)  NOT NULL
);

CREATE TABLE tests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255) NOT NULL,
    description TEXT,
    created_at  TIMESTAMP(6) NOT NULL
);

CREATE TABLE questions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_id       BIGINT       NOT NULL REFERENCES tests (id) ON DELETE CASCADE,
    question_text TEXT         NOT NULL,
    image_url     VARCHAR(2048),
    question_type VARCHAR(30)  NOT NULL
);
CREATE INDEX idx_questions_test_id ON questions (test_id);

CREATE TABLE options (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT  NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
    option_text TEXT    NOT NULL,
    is_correct  BOOLEAN NOT NULL,
    match_key   VARCHAR(100),
    order_index INTEGER
);
CREATE INDEX idx_options_question_id ON options (question_id);

CREATE TABLE quizlet_modules (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255) NOT NULL,
    description TEXT
);

CREATE TABLE flashcards (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id        BIGINT NOT NULL REFERENCES quizlet_modules (id) ON DELETE CASCADE,
    term_or_question TEXT   NOT NULL,
    answer_or_date   TEXT   NOT NULL
);
CREATE INDEX idx_flashcards_module_id ON flashcards (module_id);

CREATE TABLE test_results (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id   BIGINT       NOT NULL REFERENCES users (id),
    test_id      BIGINT       NOT NULL REFERENCES tests (id),
    score        INTEGER      NOT NULL,
    nmt_score    INTEGER,
    completed_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_test_results_student_id ON test_results (student_id);
CREATE INDEX idx_test_results_test_id ON test_results (test_id);
